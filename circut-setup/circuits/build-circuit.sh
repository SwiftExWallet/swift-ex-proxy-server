#!/usr/bin/env bash
# Compile the claim circuit at a given header-buffer size.
#
#   ./build-circuit.sh 704
#
# Generates a wrapper that includes the template and fixes the parameters, then
# compiles it. The logic lives in exactly one file, so variants cannot go stale.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")"
export PATH="$HOME/.cargo/bin:$PATH"

SIZE="${1:-704}"
[[ "$SIZE" =~ ^[0-9]+$ ]] || { echo "size must be a number" >&2; exit 1; }
(( SIZE % 64 == 0 )) || { echo "size must be a multiple of 64 (SHA-256 block size)" >&2; exit 1; }

RSA_BITS_PER_CHUNK=121     # 2 chunks must multiply without exceeding the field
RSA_CHUNKS=17              # 121 * 17 = 2057 bits, covers RSA-2048
MAX_EMAIL=255              # longest sender address the circuit will extract
MAX_SUBJECT=64             # longest subject; must hold the recovery code

OUTDIR="${OUTDIR:-build}"   # override to compile somewhere else, e.g. to compare builds
OUT="src/claim${SIZE}.circom"
cat > "$OUT" <<CIRCOM
pragma circom 2.1.6;

// GENERATED by build-circuit.sh — do not edit. Logic lives in legacy_claim.circom.
include "legacy_claim.circom";

component main { public [heirSalt] } =
    LegacyVaultClaim(${SIZE}, ${RSA_BITS_PER_CHUNK}, ${RSA_CHUNKS}, ${MAX_EMAIL}, ${MAX_SUBJECT});
CIRCOM

echo "generated $OUT"
circom "$OUT" --r1cs --wasm --O2 --output "$OUTDIR" -l node_modules \
  | grep -E "non-linear|linear constraints|Everything"
echo
echo "built $OUTDIR/claim${SIZE}.r1cs and $OUTDIR/claim${SIZE}_js/"
echo "note: a new size needs its own Phase 2 setup and a new verifier contract."
